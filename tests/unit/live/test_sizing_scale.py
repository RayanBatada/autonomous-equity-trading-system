def test_min_viable_equity_is_the_worst_price_over_weight():
    decisions = _synthetic_decisions()
    got = min_viable_equity(decisions=decisions, last_prices=_synthetic_last_prices())
    want = max(SYNTHETIC_PRICES[d.ticker] / d.target_weight for d in decisions)
    assert got == pytest.approx(want)
    # Above it, nothing is unfillable; a hair below it, something is.
    assert unfillable_names(
        decisions=decisions, account_equity=got,
        last_prices=_synthetic_last_prices(), sizing=SizingPolicy(),
    ) == []
    assert unfillable_names(
        decisions=decisions, account_equity=got * 0.99,
        last_prices=_synthetic_last_prices(), sizing=SizingPolicy(),
    ) != []


