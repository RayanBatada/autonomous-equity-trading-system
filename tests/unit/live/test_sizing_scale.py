def _translate_synth(equity, sizing):
    decisions = _synthetic_decisions()
    return translate(
        decisions=decisions, current_positions={}, account_equity=equity,
        cash=equity, last_prices=_synthetic_last_prices(), asof_date=ASOF,
        rails=_rails(), model_approved_tickers={d.ticker for d in decisions},
        sizing=sizing, adv_dollars=SYNTHETIC_ADV,
    )


def test_participation_cap_engages_at_ten_million():
    orders = _translate_synth(10_000_000.0, SizingPolicy(max_participation_of_adv=0.02))
    capped = [o for o in orders if o.capped_by == "adv_participation"]
    assert capped, "a $10M book must be capped somewhere in this universe"
    # CHEAP is the thin name: a 10% slot is $1M against $400k ADV.
    assert "CHEAP" in {o.ticker for o in capped}
    for o in capped:
        assert o.notional <= 0.02 * SYNTHETIC_ADV[o.ticker] + 1e-6


def test_participation_cap_is_inert_on_liquid_names_at_one_hundred_thousand():
    """At $100k a 2% cap touches NOTHING that trades like a large cap.

    It is not inert on the whole synthetic universe, and that is the finding,
    not a flaw in the test: CHEAP is modelled on NANC ($400k/day, in the real
    universe since 2026-05-09), and a 10% slot of $100k is $10,000 = 2.5% of
    its daily volume. So a 2% cap DOES bite at the account's current size — for
    exactly one name, the one where biting is correct. Every liquid name is
    byte-for-byte unchanged.

    The complementary proof on real data is
    test_real_decide_output_unchanged_by_a_2pct_adv_cap: across the actual
    2026-08-27 book the cap changes nothing at all, because the model has never
    picked NANC.
    """
    capped_sizing = SizingPolicy(max_participation_of_adv=0.02)
    with_cap = _translate_synth(100_000.0, capped_sizing)
    without = _translate_synth(100_000.0, SizingPolicy())

    capped = {o.ticker for o in with_cap if o.capped_by}
    assert capped == {"CHEAP"}, "only the thin ETF may be capped at $100k"

    liquid_with = [(o.ticker, o.side, o.shares) for o in with_cap if o.ticker != "CHEAP"]
    liquid_without = [(o.ticker, o.side, o.shares) for o in without if o.ticker != "CHEAP"]
    assert liquid_with == liquid_without


def test_participation_cap_untouched_when_the_thin_name_is_absent():
    """Drop the NANC analogue and a 2% cap is a total no-op at $100k."""
    decisions = [d for d in _synthetic_decisions() if d.ticker != "CHEAP"]
    kwargs = dict(
        decisions=decisions, current_positions={}, account_equity=100_000.0,
        cash=100_000.0, last_prices=_synthetic_last_prices(), asof_date=ASOF,
        rails=_rails(), model_approved_tickers={d.ticker for d in decisions},
        adv_dollars=SYNTHETIC_ADV,
    )
    with_cap = translate(sizing=SizingPolicy(max_participation_of_adv=0.02), **kwargs)
    without = translate(sizing=SizingPolicy(), **kwargs)
    assert [(o.ticker, o.side, o.shares) for o in with_cap] == \
           [(o.ticker, o.side, o.shares) for o in without]
    assert all(o.capped_by is None for o in with_cap)


def test_participation_cap_off_by_default_even_at_ten_million():
    """Default config must not start trimming a big book behind the operator's
    back — the rail ships off."""
    orders = _translate_synth(10_000_000.0, SizingPolicy())
    assert all(o.capped_by is None for o in orders)


def test_participation_cap_fails_open_on_unknown_adv():
    """A missing price history must not silently stop trading a name."""
    decisions = [StrategyDecision(asof_date=ASOF, ticker="MID", target_weight=0.10)]
    orders = translate(
        decisions=decisions, current_positions={},
        account_equity=1_000_000.0, cash=1_000_000.0,
        last_prices=_synthetic_last_prices(), asof_date=ASOF,
        rails=_rails(), model_approved_tickers={"MID"},
        sizing=SizingPolicy(max_participation_of_adv=0.02),
        adv_dollars={},           # no ADV known for anything
    )
    assert len(orders) == 1
    assert orders[0].capped_by is None


def test_participation_cap_scales_the_order_not_the_decision():
    """The cap trims the ORDER; the target is unchanged, so the next rebalance
    takes the next slice rather than the position being abandoned."""
    sizing = SizingPolicy(max_participation_of_adv=0.02)
    first = _translate_synth(10_000_000.0, sizing)
    cheap = next(o for o in first if o.ticker == "CHEAP")
    assert cheap.shares == pytest.approx(
        int(0.02 * SYNTHETIC_ADV["CHEAP"] / SYNTHETIC_PRICES["CHEAP"])
    )
    # Same decision, now partly held: the remaining delta is emitted again.
    decisions = _synthetic_decisions()
    second = translate(
        decisions=decisions, current_positions={"CHEAP": cheap.shares},
        account_equity=10_000_000.0, cash=10_000_000.0,
        last_prices=_synthetic_last_prices(), asof_date=ASOF + timedelta(days=1),
        rails=_rails(), model_approved_tickers={d.ticker for d in decisions},
        sizing=sizing, adv_dollars=SYNTHETIC_ADV,
    )
    again = next(o for o in second if o.ticker == "CHEAP")
    assert again.side == "BUY"
    assert again.shares > 0


